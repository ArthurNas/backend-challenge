export type FailureCode =
  | 'INBOX_PAYLOAD_CONFLICT'
  | 'WALLET_PLAYER_MISMATCH'
  | 'INVALID_MONEY'
  | 'INVALID_CURRENCY'
  | 'MONEY_OUT_OF_RANGE'
  | 'CURRENCY_MISMATCH'
  | 'INVALID_AMOUNT'
  | 'INSUFFICIENT_FUNDS'
  | 'REVERSAL_INSUFFICIENT_FUNDS'
  | 'INVALID_LEDGER'
  | 'INVALID_TRANSACTION_STATE'
  | 'REFERENCE_REQUIRED'
  | 'REFERENCE_MISMATCH'
  | 'INVALID_REFERENCE_KIND'
  | 'REFERENCE_NOT_PROCESSED'
  | 'REFERENCE_NOT_FOUND_EXPIRED'
